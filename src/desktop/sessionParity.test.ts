import { describe, expect, it } from "vitest";
import { ClientRuntime } from "../client/runtime/ClientRuntime";
import { CURRENT_PROTOCOL_VERSION } from "../shared/protocol/contracts";

describe("Web & Desktop Session Parity (Ticket 22)", () => {
  it("Web and Desktop observe and control the same Session and transcript without duplicating execution", async () => {
    const sharedSessionId = "shared-session-abc";
    let serverExecutionRuns = 0;

    const transcript = [
      { role: "user", content: "Initial prompt from Web" },
      { role: "assistant", content: "Response generated by server sessiond" },
    ];

    // Shared mock Gateway
    const gateway = {
      getSessionSnapshot: () => {
        return Promise.resolve({
          sessionId: sharedSessionId,
          environmentId: "local",
          messageCount: transcript.length,
          messages: [...transcript],
          seq: transcript.length,
        });
      },
      submitPrompt: (prompt: string) => {
        serverExecutionRuns++;
        transcript.push({ role: "user", content: prompt });
        transcript.push({ role: "assistant", content: `Echo: ${prompt}` });
        return Promise.resolve();
      },
    };

    // Client 1: Web
    const webRuntime = new ClientRuntime({
      catalogFetcher: () => Promise.resolve([{ id: "local", name: "Local" }]),
      descriptorFetcher: () => Promise.resolve({
        id: "local",
        name: "Local",
        kind: "local",
        protocolVersion: CURRENT_PROTOCOL_VERSION,
        capabilities: { streaming: true },
        status: "connected",
      }),
      sessionSnapshotFetcher: () => gateway.getSessionSnapshot(),
    });

    // Client 2: Desktop
    const desktopRuntime = new ClientRuntime({
      catalogFetcher: () => Promise.resolve([{ id: "local", name: "Local" }]),
      descriptorFetcher: () => Promise.resolve({
        id: "local",
        name: "Local",
        kind: "local",
        protocolVersion: CURRENT_PROTOCOL_VERSION,
        capabilities: { streaming: true },
        status: "connected",
      }),
      sessionSnapshotFetcher: () => gateway.getSessionSnapshot(),
    });

    await webRuntime.loadCatalog();
    await desktopRuntime.loadCatalog();

    // Both attach to same session
    const webSnapshot = await webRuntime.switchSession("local", { id: sharedSessionId, cwd: "/app" });
    const desktopSnapshot = await desktopRuntime.switchSession("local", { id: sharedSessionId, cwd: "/app" });

    expect(webSnapshot?.sessionId).toBe(sharedSessionId);
    expect(desktopSnapshot?.sessionId).toBe(sharedSessionId);
    expect(webSnapshot?.messages).toEqual(desktopSnapshot?.messages);

    // Desktop submits prompt via gateway
    await gateway.submitPrompt("Follow-up from Desktop");
    expect(serverExecutionRuns).toBe(1);

    // Both re-sync and observe exact same updated transcript
    const webUpdated = await webRuntime.switchSession("local", { id: sharedSessionId, cwd: "/app" });
    const desktopUpdated = await desktopRuntime.switchSession("local", { id: sharedSessionId, cwd: "/app" });

    expect(webUpdated?.messages).toHaveLength(4);
    expect(desktopUpdated?.messages).toHaveLength(4);
    expect(webUpdated?.messages).toEqual(desktopUpdated?.messages);
  });
});
